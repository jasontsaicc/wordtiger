const PLACEHOLDER = /\{\{\s*(\w+)\s*\}\}/g;

/** 單次展開 placeholders，避免替換值再次被解析。 */
export function renderTemplate(
  template: string,
  vars: Record<string, string>,
): string {
  return template.replace(PLACEHOLDER, (whole, key: string) =>
    key in vars ? vars[key]! : whole,
  );
}

const CJK = /[\u4e00-\u9fff]/;
/** 拒絕模型截斷的片語，避免建立無法匹配的 key。 */
const ELLIPSIS = /…|\.\.\./;

/** 只取「帶走」裡可當作詞庫 key 的英文片語或句型。 */
export function extractTakeaway(response: string): string | null {
  const line = response.split(/\r?\n/).find((item) => item.trim().startsWith('帶走｜'));
  if (!line) return null;

  // 掃描所有區段並排除 CJK，容忍重複前綴與缺少片語的回覆。
  const phrase = line.split('｜').slice(1)
    .map((part) => part.trim().replace(/^`|`$/g, ''))
    .find((part) => /[a-z]/i.test(part) && !CJK.test(part)) ?? '';

  if (!phrase || ELLIPSIS.test(phrase)) return null;
  return phrase.slice(0, 160);
}

export interface QuizExtract {
  choices: [string, string, string];
  right: 0 | 1 | 2;
}

const OPTION_PREFIX = '選項｜';
const ANSWER_PREFIX = '答案｜';

/** 三段互不相同的非空選項才算選項行;字首可有可無。 */
function splitChoices(line: string): [string, string, string] | null {
  const body = line.startsWith(OPTION_PREFIX) ? line.slice(OPTION_PREFIX.length) : line;
  const choices = body.split('｜').map((s) => s.trim());
  if (choices.length !== 3 || choices.some((c) => !c)) return null;
  if (new Set(choices).size !== 3) return null;
  return choices as [string, string, string];
}

/**
 * 只認回應開頭兩行的選項與答案；任一條件不成立就回 null，寧可不出題。
 * `right` 是選項在原始順序裡的索引（0-based），畫面洗牌後的位置由呼叫端另外算。
 */
export function extractQuiz(text: string): QuizExtract | null {
  const lines = text.split(/\r?\n/);
  let start = 0;
  while (start < lines.length && lines[start]!.trim() === '') start++;

  const optionLine = lines[start]?.trim() ?? '';
  const answerLine = lines[start + 1]?.trim() ?? '';
  // 模型會把「選項｜」讀成欄位說明而不照抄,所以錨點是下一行的「答案｜」;
  // 選項行有沒有字首都收,反正正文行切不出剛好三段。
  if (!answerLine.startsWith(ANSWER_PREFIX)) return null;

  const choices = splitChoices(optionLine);
  if (!choices) return null;

  // 規定是「答案｜2」,但模型也寫過「答案｜正確選項是第1個」;取第一個 1-3 的數字。
  const answer = Number(answerLine.slice(ANSWER_PREFIX.length).match(/[1-3]/)?.[0]);
  if (!answer) return null;

  return { choices, right: (answer - 1) as 0 | 1 | 2 };
}

/**
 * 無條件剝除開頭的選項／答案行，不管抽取有沒有成功。
 * 模型只吐了選項沒吐答案時，extractQuiz 會回 null，但那行仍必須剝掉，
 * 否則壞題直接印在卡片上。只認開頭的行，正文中間的同名行視為內容不動它。
 */
export function stripQuiz(text: string): string {
  const lines = text.split(/\r?\n/);
  let start = 0;
  while (start < lines.length && lines[start]!.trim() === '') start++;

  let end = start;
  // 沒有「選項｜」字首的選項行,靠下一行的「答案｜」認出來。
  if (splitChoices(lines[end]?.trim() ?? '')
    && lines[end + 1]?.trim().startsWith(ANSWER_PREFIX)) end++;
  if (lines[end]?.trim().startsWith(OPTION_PREFIX)) end++;
  if (lines[end]?.trim().startsWith(ANSWER_PREFIX)) end++;
  if (end === start) return text;

  return lines.slice(end).join('\n');
}
